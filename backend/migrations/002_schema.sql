-- Schema do corpus farmacológico. docs/DATABASE.md §2.
--
-- Embedding em 1536 dimensões (não 3072): o índice HNSW do tipo `vector`
-- só suporta até 2000 dimensões. Redução via Matryoshka (MRL) com
-- normalização L2 manual no ETL — ver docs/DATABASE.md "Por que 1536 e
-- não 3072" e docs/DIVERGENCIAS.md §3.

create table documento (
  id            bigint generated by default as identity primary key,
  titulo        text not null,
  tipo_fonte    text not null check (tipo_fonte in ('livro','bula')),
  referencia    text not null,          -- "Spinosa et al. (2017)"
  indice_versao text not null,          -- data + hash do corpus
  criado_em     timestamptz not null default now()
);

create table chunk (
  id           bigint generated by default as identity primary key,
  chunk_id     text not null unique,    -- "spinosa-c22-p574-003"
  documento_id bigint not null references documento(id) on delete cascade,
  texto        text not null,
  texto_hash   text not null,           -- idempotência do ETL
  capitulo     text,
  pagina       int,
  farmacos     text[] not null default '{}',
  especies     text[] not null default '{}',
  tokens       int not null,
  embedding    vector(1536) not null,   -- gemini-embedding-001, MRL 1536
  fts          tsvector generated always as (to_tsvector('portuguese', texto)) stored,
  criado_em    timestamptz not null default now()
);
